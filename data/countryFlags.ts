export function getCountryCode(name: string | undefined | null): string | null {
  if (!name) return null;
  return COUNTRY_CODE_BY_NAME[name] ?? null;
}

/**
 * URL d'un drapeau PNG carré 80x80 (flagcdn supporte aussi w20/w40/h60 etc.)
 * On affichera dans une vue avec borderRadius pour le rendu rond.
 */
export function getFlagUrl(countryName: string | undefined | null, size: 40 | 80 | 160 = 80): string | null {
  const code = getCountryCode(countryName);
  if (!code) return null;
  return `https://flagcdn.com/w${size}/${code}.png`;
}
